import React, { useState, Suspense } from 'react';
import { Canvas } from '@react-three/fiber';
import { OrbitControls, Environment, PerspectiveCamera } from '@react-three/drei';
import { Controls } from './components/Controls';
import { WeatherCard } from './components/WeatherCard';
import { WeatherConfig, DEFAULT_CONFIG } from './types';

function App() {
  const [config, setConfig] = useState<WeatherConfig>(DEFAULT_CONFIG);
  const [exploded, setExploded] = useState(false);

  return (
    <div className="flex h-screen w-screen bg-slate-950">
      {/* Sidebar Controls */}
      <Controls 
        config={config} 
        setConfig={setConfig} 
        exploded={exploded}
        setExploded={setExploded}
      />

      {/* Main Canvas Area */}
      <div className="flex-1 relative cursor-grab active:cursor-grabbing">
        <div className="absolute top-6 left-6 z-10 pointer-events-none">
             <h2 className="text-white/50 font-bold text-sm tracking-widest uppercase">Preview Canvas</h2>
        </div>

        <Canvas>
          <PerspectiveCamera makeDefault position={[0, 0, 8]} fov={50} />
          
          <ambientLight intensity={0.5} />
          <spotLight position={[10, 10, 10]} angle={0.15} penumbra={1} intensity={1} />
          <pointLight position={[-10, -10, -10]} intensity={0.5} />
          
          <Suspense fallback={null}>
            <group position={[0, 0, 0]}>
              <WeatherCard config={config} exploded={exploded} />
            </group>
            
            <Environment preset="city" />
          </Suspense>

          <OrbitControls 
            enablePan={false} 
            minPolarAngle={Math.PI / 4} 
            maxPolarAngle={Math.PI / 1.5}
            minAzimuthAngle={-Math.PI / 3}
            maxAzimuthAngle={Math.PI / 3}
          />
        </Canvas>

        {/* Instructions Overlay */}
        <div className="absolute bottom-6 right-6 z-10 bg-black/30 backdrop-blur-md px-4 py-3 rounded-lg border border-white/10 text-right">
             <p className="text-xs text-white/70">Drag to rotate • Scroll to zoom</p>
             <p className="text-[10px] text-white/40 mt-1">Generated by Gemini 2.5 Flash</p>
        </div>
      </div>
    </div>
  );
}

export default App;
